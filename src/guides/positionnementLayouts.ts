// Defensive layouts of the positioning guide, one per configuration and per
// attacking zone. Pure data, shared by the guide page and the content export
// (`scripts/content/`), so it lives outside the component file.
import type { RoleColorKey } from '../constants/positions';

export type ZoneTab = 'zone4' | 'zone3' | 'zone2';
export type ZoneId = 'P1' | 'P2' | 'P3' | 'P4' | 'P5' | 'P6';

export type DefensePlayer = {
  zoneId: ZoneId;
  x: number;
  y: number;
  sub?: string;
  // Optional overrides for the colour and label shown.
  role?: RoleColorKey;
  label?: string;
};

export type DefenseZone = {
  x: number; y: number; w: number; h: number;
  posNumber: ZoneId;
  // Optional override of the zone fill colour (defaults to posNumber's role).
  role?: RoleColorKey;
  // Optional manual label colour (defaults to neutral fallback).
  labelRole?: RoleColorKey;
  // Optional manual label position (already final; no auto-offset).
  labelPos?: { x: number; y: number };
};

export type Shot = {
  toX: number;
  toY: number;
};

export type DefenseLayout = {
  ballX: number;
  ballY: number;
  players: DefensePlayer[];
  zones: DefenseZone[];
  mainShot: Shot;
  altShots: Shot[];
};

const Z = (zoneId: ZoneId, x: number, y: number, w: number, h: number): DefenseZone =>
  ({ x, y, w, h, posNumber: zoneId });

